import { describe,expect,it } from 'vitest'
import { Chapter1Fixture } from '../../tests/helpers/chapter1'
import { chapter1Action,chapter1Available,chapter1Current,chapter1Gate,chapter1Lifecycle,chapter1OptionsFor } from './chapter1'
import { normalizeSave } from './engine'
import { continueFromChapter1 } from './chapter2Access'
import { newGame } from './types'

describe('official playable 18-scene structure',()=>{
  it('completes all 18 scenes through real choices and actions, then waits for explicit Chapter 2 Continue',()=>{
    const f=new Chapter1Fixture().opening()
    const relationships=structuredClone(f.save.relationships),group=structuredClone(f.save.prologue!.scene01!.groupMessages)
    expect(f.save.chapter1?.sender.messages).toHaveLength(1)
    f.run()
    expect(f.save.chapter1?.completed).toEqual(Array.from({length:15},(_,i)=>i+4))
    expect(f.save.chapter1?.chapterComplete).toBe(true)
    expect(f.save.chapter2Access).toBeUndefined()
    expect(f.save.relationships).toEqual(relationships)
    expect(f.save.prologue!.scene01!.groupMessages).toEqual(group)
    expect(f.save.prologue!.scene01!.groupMembers?.lucas).toBe(false)
    expect(f.save.knowledge.characters.nora).toEqual([])
    expect(f.save.knowledge.characters.eli).toEqual([])
    expect(f.save.knowledge.characters.sophie).not.toContain('CH1-SENDER-WARNING-DISCLOSED')
    expect(Object.values(f.save.evidence).every(e=>!e.verified)).toBe(true)
    const started=continueFromChapter1(f.save,f.now)
    expect(started.chapter2Access?.unknownCreated).toBe(false)
    expect(started.prologue).toEqual(f.save.prologue)
    expect(started.evidence).toEqual(f.save.evidence)
    expect(continueFromChapter1(started,f.now)).toBe(started)
  })
  for(const n of Array.from({length:15},(_,i)=>i+4))it(`scene ${n} cannot complete merely by rendering, revisiting or premature advance`,()=>{
    const f=new Chapter1Fixture().opening();if(n>4)f.run(n-1)
    expect(chapter1Current(f.save)).toBe(n)
    const before=structuredClone(f.save)
    f.act({type:'advance'})
    expect(f.save).toEqual(before)
    expect(chapter1Gate(f.save).some(g=>!g.done)).toBe(true)
    expect(continueFromChapter1(f.save,f.now)).toBe(f.save)
  })
  it('keeps Archive dormant, unlocks a first record only after a manual public inspection, and hides future claims',()=>{
    const f=new Chapter1Fixture().act({type:'tick'})
    expect(chapter1Available(f.save)).toEqual([])
    f.inspect('CH1-ROLE').step('first-record')
    expect(chapter1Lifecycle(f.save)).toBe('installed_dormant')
    f.opening()
    expect(chapter1Available(f.save).map(r=>r.id)).toEqual(['CH1-PUBLIC'])
    f.step('first-record');expect(chapter1Available(f.save)).toHaveLength(1)
    f.inspect('CH1-PUBLIC').step('first-record')
    expect(chapter1Lifecycle(f.save)).toBe('first_record_available')
    f.inspect('CH1-FIRST');expect(chapter1Lifecycle(f.save)).toBe('investigation_active')
    expect(chapter1Available(f.save).some(r=>r.id==='CH1-CLAIM')).toBe(false)
  })
  for(const branch of ['ignore','question','boundary','cautious'])it(`sender ${branch} is selected explicitly and remains private across reload`,()=>{
    const f=new Chapter1Fixture().opening().act({type:'read-sender'}),before=f.save.chapter1!.sender.messages.length
    f.act({type:'draft',key:'sender',id:branch})
    expect(f.save.chapter1!.sender.messages).toHaveLength(before)
    f.act({type:'send',key:'sender'})
    expect(f.save.chapter1!.sender.messages).toHaveLength(before+(branch==='ignore'?0:1))
    f.save=normalizeSave(JSON.parse(JSON.stringify(f.save)));f.settle().act({type:'tick'})
    expect(f.save.chapter1!.sender.branch).toBe(branch)
    expect(f.save.chapter1!.sender.disclosed).toBe(false)
    expect(f.save.chapter1!.sender.messages.filter(m=>m.sender==='unknown')).toHaveLength(1)
  })
  it('accepts harmless missing dialogue responses without treating them as identity, evidence or consent',()=>{
    const f=new Chapter1Fixture().opening().run(10)
    f.inspect('CH1-INDEX').inspect('CH1-INDEX-NOTE').act({type:'interpret',key:'index',id:'equal'})
    expect(f.save.chapter1?.flags).not.toContain('index-counted')
    f.act({type:'interpret',key:'index',id:'14-13'}).advance()
    f.send('eli-intro','introduce').send('eli','decline').step('technical-ack').advance()
    expect(chapter1Current(f.save)).toBe(13)
    expect(f.save.knowledge.characters.eli).toEqual([])
    expect(f.save.messages.some(m=>m.sender==='eli')).toBe(false)
  })
  it('persists drafts, comparisons and chapter completion; keeps old saves untouched and rejects malformed state',()=>{
    const f=new Chapter1Fixture().opening().run(6)
    f.act({type:'draft',key:'nora',id:'skeptical'})
    const restored=normalizeSave(JSON.parse(JSON.stringify(f.save)))
    expect(restored.chapter1?.drafts.nora).toBe('skeptical')
    expect(chapter1OptionsFor(restored,'nora')).toHaveLength(4)
    expect(chapter1Action({...newGame(),narrativePlan:undefined},{type:'tick'}).chapter1).toBeUndefined()
    expect(()=>normalizeSave({...restored,chapter1:{...restored.chapter1,completed:[4,6]}})).toThrow('Invalid Chapter 1')
    f.run();expect(normalizeSave(JSON.parse(JSON.stringify(f.save))).chapter1?.chapterComplete).toBe(true)
  })
  it('discloses the warning to Sophie only after an explicit Send and does not share any files or identity',()=>{
    const f=new Chapter1Fixture().opening().act({type:'read-sender'})
    const old=f.save.prologue!.scene01!.messages.length
    f.act({type:'draft',key:'disclose',id:'tell'})
    expect(f.save.prologue!.scene01!.messages).toHaveLength(old)
    expect(f.save.knowledge.characters.sophie).not.toContain('CH1-SENDER-WARNING-DISCLOSED')
    f.act({type:'send',key:'disclose'})
    expect(f.save.knowledge.characters.sophie).toContain('CH1-SENDER-WARNING-DISCLOSED')
    expect(f.save.prologue!.scene01!.messages.at(-1)?.sender).toBe('player')
    f.settle();expect(f.save.prologue!.scene01!.messages.at(-1)?.text).toBe("Thank you for telling me. I don't know who sent that.")
    expect(f.save.knowledge.characters.maya).not.toContain('CH1-SENDER-WARNING-DISCLOSED')
    expect(chapter1OptionsFor(f.save,'disclose')).toEqual([])
  })
  it('retains and delivers an outstanding source-request reply if the player continues Chapter 2 quickly',()=>{
    const f=new Chapter1Fixture().opening().run(15)
    f.act({type:'draft',key:'original',id:'nora'}).act({type:'send',key:'original'}).advance()
    for(const [key,id] of [['diff','observed'],['claim','reported'],['source','unknown'],['theory','interpretation']])f.act({type:'draft',key:'board-'+key,id})
    f.step('board-classified').step('summary-saved').advance().inspect('CH1-ROLE').act({type:'interpret',key:'ending',id:'cautious'}).advance()
    const due=f.save.pendingEvents.find(e=>e.id==='CH1-NORA-REQUEST')!
    expect(due).toBeTruthy()
    const started=continueFromChapter1(f.save,f.now)
    const delivered=chapter1Action(started,{type:'tick'},due.dueAt)
    expect(delivered.messages.filter(m=>m.id==='CH1-NORA-REQUEST')).toHaveLength(1)
    expect(delivered.chapter2Access).toEqual(started.chapter2Access)
    expect(chapter1Action(delivered,{type:'tick'},due.dueAt).messages.filter(m=>m.id==='CH1-NORA-REQUEST')).toHaveLength(1)
  })
})
