import 'fake-indexeddb/auto'
import { describe, expect, it } from 'vitest'
import { dueEvent, registerPlayer } from './engine'
import { loadGame, writeGame } from './save'
import { advanceSlice, answerComparison, answerEditor, inspectPreview, openSliceInbox, readBrief, saveLead, sendTip, setTipDraft } from './slice'
import { answerSourceStatus, askMayaAboutRow, closeShareWithoutSend, continueToEditorNote, continueToPermissionSheet, continueToShare, decideConnection, draftPhase03b, enterAfterEditor, enterPublicSources, inspectSourceStatus, onEditorChecked, openOptionalConnections, reopenConnections, sendPhase03b, showEditorHint } from './phase03b'
import { newGame, type GameSave } from './types'

function deliver(state: GameSave, at = 1_000_000) {
  for (let i=0;i<30;i++) {
    const next = dueEvent(state,at)
    if (next === state) break
    state = next
  }
  return state
}
function atEditor(mode: 'anonymous' | 'handle' = 'anonymous') {
  let state = registerPlayer(newGame(),'Rae')
  state = advanceSlice(state,0)
  state = readBrief(state)
  state = advanceSlice(state,0)
  state = inspectPreview(state,1)
  state = advanceSlice(state,1)
  state = advanceSlice(state,2)
  state = answerComparison(state,'escort')
  state = saveLead(state,'P-S07-C',3)
  state = setTipDraft(state,mode,mode === 'handle' ? 'RaeReader' : '')
  state = advanceSlice(state,4)
  state = sendTip(state,100)
  state = deliver(state)
  state = openSliceInbox(state)
  return advanceSlice(state,100_001)
}

describe('Episode 01 S12–S15 source and recipient boundaries', () => {
  it('checks the public editor channel, offers hints and keeps an optional question behind Send', () => {
    let state = atEditor()
    expect(state.e01?.sceneId).toBe('E01-S12')
    expect(enterAfterEditor(state,100_002)).toBe(state)
    state = showEditorHint(state)
    expect(state.e01?.editorHintCount).toBe(1)
    state = answerEditor(state,'name-photo')
    expect(state.e01?.editorChecked).toBe(false)
    state = onEditorChecked(answerEditor(state,'code-route'),100_002)
    expect(state.deliveredEvents).toContain('EV-E01-S12-EDITOR-CHECK')
    expect(state.knowledge.player).not.toContain('K02')
    state = deliver(state)
    state = draftPhase03b(state,'P-S12-C')
    expect(state.messages.find(message => message.id === 'player.P-S12-C')).toBeUndefined()
    state = sendPhase03b(state,100_003)
    expect(state.messages.filter(message => message.id === 'player.P-S12-C')).toHaveLength(1)
    expect(state.relationships.maya.trust).toBe(49)
    expect(state.relationships.maya.suspicion).toBe(22)
    expect(sendPhase03b(state,100_004)).toBe(state)
    state = deliver(state)
    state = enterAfterEditor(state,100_005)
    expect(state.e01?.sceneId).toBe('E01-S13')
    expect(state.e01?.s13Asked).toBeUndefined()
    expect(state.messages.some(message => message.id.startsWith('EV-E01-P03B:S13_OPEN'))).toBe(false)
  })

  it.each(['image','text'] as const)('issues one R02 only for explicitly sent %s content and survives reload', async scope => {
    let state = atEditor('handle')
    state = deliver(onEditorChecked(answerEditor(state,'code-route'),100_002))
    state = deliver(enterAfterEditor(state,100_003))
    state = askMayaAboutRow(state,100_004)
    state = deliver(state)
    state = draftPhase03b(state,'P-S13-A')
    expect(state.knowledge.characters.maya).not.toContain('S13.public-source-location')
    state = sendPhase03b(state,100_005)
    expect(state.messages.find(message => message.id === 'player.P-S13-A')?.recipient).toBe('maya')
    state = deliver(state)
    state = deliver(continueToShare(state,100_006))
    expect(state.e01?.sceneId).toBe('E01-S14')
    const id = scope === 'image' ? 'C02-SHARE.A' : 'C02-SHARE.B'
    state = draftPhase03b(state,id)
    expect(state.deliveredEvents).not.toContain('R02')
    state = sendPhase03b(state,100_007)
    expect(state.deliveredEvents.filter(event => event === 'R02')).toHaveLength(1)
    expect(state.e01?.s14Share).toBe(scope)
    expect(state.messages.find(message => message.id === `player.${id}`)?.attachmentIds).toEqual(scope === 'image' ? ['E001.cropped-public-escort-row'] : undefined)
    expect(state.knowledge.characters.maya).toContain('R02.public-escort-row')
    expect(state.knowledge.characters.maya).not.toContain('K02')
    expect(sendPhase03b(state,100_008)).toBe(state)
    state = deliver(state)
    state = continueToEditorNote(state,100_009)
    expect(state.e01?.sceneId).toBe('E01-S15')
    expect(state.pendingEvents.some(event => event.id.startsWith('EV-E01-P03B:S15_DIRECT'))).toBe(true)
    await writeGame(state)
    const restored = await loadGame()
    expect(restored.error).toBeUndefined()
    expect(restored.save.e01?.sceneId).toBe('E01-S15')
    expect(restored.save.deliveredEvents.filter(event => event === 'R02')).toHaveLength(1)
    expect(restored.save.e01?.s14Share).toBe(scope)
  })

  it('keeps the skeptical quiet route and a closed share sheet out of Maya knowledge', () => {
    let state = atEditor()
    state = deliver(onEditorChecked(answerEditor(state,'code-route'),100_002))
    state = enterAfterEditor(state,100_003)
    expect(state.e01?.sceneId).toBe('E01-S13')
    state = continueToShare(state,100_004)
    expect(state.e01?.sceneId).toBe('E01-S14')
    expect(state.pendingEvents.some(event => event.id.startsWith('EV-E01-P03B:S14_REQUEST'))).toBe(false)
    state = draftPhase03b(state,'C02-SHARE.C')
    expect(state.messages.filter(message => message.id.startsWith('player.C02'))).toHaveLength(0)
    state = closeShareWithoutSend(state)
    expect(state.e01?.s14Share).toBe('none')
    expect(state.deliveredEvents).not.toContain('R02')
    expect(state.knowledge.characters.maya).not.toContain('R02.public-escort-row')
    state = continueToEditorNote(state,100_005)
    expect(state.e01?.sceneId).toBe('E01-S15')
    expect(state.pendingEvents.some(event => event.id.startsWith('EV-E01-P03B:S15_DIRECT'))).toBe(false)
    state = enterPublicSources(state)
    expect(state.e01?.sceneId).toBe('E01-S18')
    expect(state.e01?.s18Route).toBe('public')
    expect(state.deliveredEvents).not.toContain('R03')
    expect(answerSourceStatus(state,'preview')).toBe(state)
    state = inspectSourceStatus(state,'preview')
    expect(answerSourceStatus(state,'wrong')).toBe(state)
    state = answerSourceStatus(state,'preview')
    expect(state.e01?.sceneId).toBe('E01-S19')
    expect(state.knowledge.player).not.toContain('K02')
  })

  it('keeps the two optional permissions independent and opens Archive only on acceptance', () => {
    let state = atEditor('handle')
    state = deliver(onEditorChecked(answerEditor(state,'code-route'),100_002))
    state = deliver(enterAfterEditor(state,100_003))
    state = deliver(askMayaAboutRow(state,100_004))
    state = draftPhase03b(state,'P-S13-A')
    state = deliver(sendPhase03b(state,100_005))
    state = deliver(continueToShare(state,100_006))
    state = draftPhase03b(state,'C02-SHARE.B')
    state = deliver(sendPhase03b(state,100_007))
    state = deliver(continueToEditorNote(state,100_008))
    state = deliver(openOptionalConnections(state,100_009))
    expect(state.e01?.sceneId).toBe('E01-S16')
    expect(state.deliveredEvents).not.toContain('R03')
    state = continueToPermissionSheet(state)
    expect(state.e01?.sceneId).toBe('E01-S17')
    state = decideConnection(state,'messages',false)
    state = decideConnection(state,'archive',true)
    expect(state.deliveredEvents).not.toContain('CONN-E01-01')
    expect(state.deliveredEvents.filter(id => id === 'R03')).toHaveLength(1)
    expect(state.knowledge.player).toContain('archive.invitation.accepted')
    expect(decideConnection(state,'archive',true)).toBe(state)
    state = enterPublicSources(state)
    expect(state.e01?.s18Route).toBe('archive')
    state = reopenConnections(state)
    state = decideConnection(state,'messages',true)
    expect(state.deliveredEvents.filter(id => id === 'CONN-E01-01')).toHaveLength(1)
    expect(state.deliveredEvents.filter(id => id === 'R03')).toHaveLength(1)
    expect(state.knowledge.characters.maya).not.toContain('K02')
  })
})
