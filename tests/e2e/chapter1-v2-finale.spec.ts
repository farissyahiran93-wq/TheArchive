async function reachCall(page:Page){
  await page.getByRole('button',{name:'Open TRACE',exact:true}).click()
  for(const title of ['Transfer Register','Public Finding Aid','Box Inventory','Issuer reference','Case Board'])await page.getByRole('button',{name:title,exact:true}).click()
  await page.getByRole('button',{name:'Record private conclusion'}).click()
  await page.getByRole('button',{name:/public box index points to GH-DSC-03-A/}).click()
  await page.getByRole('button',{name:'Save privately'}).click()
  await page.getByRole('button',{name:'Return to Home'}).click()
  await page.clock.runFor(3000)
  await expect(page.getByRole('dialog',{name:'Incoming call from Sophie'})).toBeVisible()
}
test('Scene 10 returns Home, rings, and requires explicit call responses',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await seedScene(page,finaleFixture(),{pauseClock:true})
  await reachCall(page)
  await page.getByRole('button',{name:'Answer',exact:true}).tap()
  await expect(page.getByRole('heading',{name:'Sophie Mercer'})).toBeVisible()
  await expect(page.locator('.phone-call-status')).toBeVisible()
  const mobileSize=await page.locator('.phone-call-screen').evaluate(el=>({width:el.clientWidth,scrollWidth:el.scrollWidth,height:el.clientHeight,scrollHeight:el.scrollHeight}))
  expect(mobileSize.scrollWidth).toBeLessThanOrEqual(mobileSize.width+1)
  expect(mobileSize.scrollHeight).toBeLessThanOrEqual(mobileSize.height+1)
  await page.getByRole('button',{name:"I'm listening."}).click()
  await page.getByRole('button',{name:'Say this'}).click()
  await page.clock.runFor(5000)
  await expect(page.locator('.phone-call-status')).toContainText('00:05')
  await expect(page.getByText("It's your number.")).toBeVisible()
  await page.reload()
  await page.getByRole('button',{name:'Unlock phone',exact:true}).click()
  await page.getByRole('button',{name:'Open TRACE',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Sophie Mercer'})).toBeVisible()
  await expect(page.getByText("It's your number.")).toBeVisible()
  await page.getByRole('button',{name:'Do you know who wrote it?'}).click()
  await page.getByRole('button',{name:'Say this'}).click()
  await page.clock.runFor(4000)
  await expect(page.getByText('DO NOT CONTACT THE STARRED NUMBER.')).toBeVisible()
  await page.getByRole('button',{name:'Continue',exact:true}).click()
  await expect(page.locator('.call-subtitle').filter({hasText:'But...'})).toBeVisible()
  await page.getByRole('button',{name:'Continue',exact:true}).click()
  await expect(page.locator('.call-subtitle').filter({hasText:'I already did.'})).toBeVisible()
  await page.clock.runFor(1000)
  await page.getByRole('button',{name:'End call'}).click()
  await page.clock.runFor(1200)
  await expect(page.getByRole('heading',{name:'CHAPTER 1 COMPLETE'})).toBeVisible()
  await expect(page.getByText('THE PEOPLE HE LEFT BEHIND')).toBeVisible()
  await page.getByRole('button',{name:'Continue to Chapter Select'}).click()
  await expect(page.getByRole('button',{name:/CHAPTER 2 THE PEOPLE HE LEFT BEHIND/})).toBeEnabled()
})
test('desktop call remains usable without audio and after decline',async({page})=>{
  await page.setViewportSize({width:1280,height:800})
  await page.addInitScript(()=>{Object.defineProperty(window,'AudioContext',{value:undefined,configurable:true})})
  await seedScene(page,finaleFixture(),{pauseClock:true})
  await reachCall(page)
  await expect(page.getByRole('button',{name:'Decline'})).toBeVisible()
  await page.getByRole('button',{name:'Decline'}).click()
  await expect(page.locator('.call-subtitle').filter({hasText:'Please call me'})).toBeVisible()
  await page.getByRole('button',{name:'Call Sophie back'}).click()
  await expect(page.getByRole('heading',{name:'Sophie Mercer'})).toBeVisible()
  await expect(page.locator('.call-subtitle').filter({hasText:'Thank you for calling back'})).toBeVisible()
  const size=await page.locator('.phone-call-screen').evaluate(el=>({width:el.clientWidth,scrollWidth:el.scrollWidth,height:el.clientHeight,scrollHeight:el.scrollHeight}))
  expect(size.scrollWidth).toBeLessThanOrEqual(size.width+1)
  expect(size.scrollHeight).toBeLessThanOrEqual(size.height+1)
})
