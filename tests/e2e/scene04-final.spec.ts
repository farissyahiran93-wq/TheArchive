import {test,expect,type Page} from '@playwright/test'
import {Scene04Fixture} from '../helpers/scene04Final'
import {seedScene,openSophie,sceneReply} from './scene01-helper'
test.use({reducedMotion:'reduce'})
const click=async(page:Page,name:string)=>page.getByRole('button',{name,exact:true}).first().click()
const flush=async(page:Page)=>page.waitForFunction(()=>!sessionStorage.getItem('the-archive-reboot:pending-save:v1'))

test('Scene 04 full manual route: article, skipped optional group, index choices, final Sophie and deliberate Scene 05 entry',async({page})=>{
  test.setTimeout(150000)
  await page.setViewportSize({width:320,height:720})
  await seedScene(page,new Scene04Fixture().at('OPEN-S04-C02').save)
  await openSophie(page)
  await sceneReply(page,'What thing?')
  await expect(page.getByRole('article',{name:'Public article link'})).toBeVisible()
  await click(page,'NOT NOW')
  await flush(page);await page.reload();await click(page,'Enter the archive');await openSophie(page)
  await click(page,'READ ARTICLE')
  await expect(page.getByRole('region',{name:'Greyhaven Bulletin public article'})).toBeVisible()
  await expect(page.locator('[data-paragraph]')).toHaveCount(6)
  await page.screenshot({path:test.info().outputPath('public-article-320.png')})
  await click(page,'By Nora Vance')
  await expect(page.getByRole('dialog',{name:'Nora Vance public byline'})).toBeVisible()
  await expect(page.getByText('No private contact information is provided.',{exact:false})).toBeVisible()
  await click(page,'Close article information')
  await click(page,'Updated: Yesterday')
  await expect(page.getByText('This page displays a later update time. A change log is not shown on this page.')).toBeVisible()
  await click(page,'Close article information')
  await click(page,'MARK AS READ');await click(page,'SAVE PUBLIC ARTICLE');await click(page,'RETURN TO SOPHIE')
  await page.clock.runFor(120000)
  await sceneReply(page,'It says less than the headline makes you expect.')
  await sceneReply(page,'That must be exhausting.')
  await sceneReply(page,'The article confirms people are worried. Not what happened.')
  await sceneReply(page,'That could be a normal correction.')
  await click(page,'READ GROUP LATER');await page.clock.runFor(120000)
  await sceneReply(page,'Do you have a screenshot from when it was published?')
  await sceneReply(page,"That's understandable.")
  await click(page,'Open The Archive')
  await expect(page.getByRole('region',{name:'Scene 04 Archive index'})).toBeVisible()
  await click(page,'OPEN INDEX')
  await expect(page.getByText('CONTENT PREVIEW: UNAVAILABLE IN THIS INDEX VIEW',{exact:false})).toBeVisible()
  await expect(page.getByText('JUNE ELLIS',{exact:false})).toHaveCount(0)
  await page.screenshot({path:test.info().outputPath('archive-index-320.png')})
  await click(page,"It's a reference that might be connected.");await click(page,'Record selection')
  await expect(page.getByRole('status')).toContainText('unverified')
  await click(page,'ACKNOWLEDGE LIMITATIONS')
  await click(page,"Don't save either item yet.");await click(page,'Record selection')
  await expect(page.getByRole('button',{name:'REVIEW VERSION HISTORY',exact:true})).toBeDisabled()
  await click(page,'RETURN TO DEVICE');await page.clock.runFor(10000)
  await openSophie(page);await page.clock.runFor(120000)
  await expect(page.locator('[data-scene-node="OPEN-S04-C12"]')).toBeVisible()
  await sceneReply(page,'Has it helped to talk about the article?')
  await sceneReply(page,'I found a saved reference that may relate to the article.')
  await sceneReply(page,"In a recovered index on this device. I haven't verified its source.")
  await sceneReply(page,'You miss him.')
  await sceneReply(page,"I'm sure you still are.")
  await sceneReply(page,"I won't. Talk later.")
  await expect(page.locator('.opening-bubble').last()).toHaveText('Goodnight.')
  await click(page,'Go home');await click(page,'Open The Archive')
  await expect(page.getByRole('button',{name:'REVIEW VERSION HISTORY',exact:true})).toBeEnabled()
  await click(page,'REVIEW VERSION HISTORY')
  await expect(page.getByRole('region',{name:'Chapter 1 investigation'})).toHaveAttribute('data-chapter1-scene','5')
})

test('Scene 04 optional group plays once and returns to the correct Sophie decision',async({page})=>{
  await seedScene(page,new Scene04Fixture().at('OPEN-S04-GROUP-OFFER').save)
  await openSophie(page)
  await click(page,'Open FIND DANIEL →');await page.clock.runFor(120000)
  await expect(page.locator('[data-scene-node="OPEN-S04-C07"]')).toBeVisible()
  await expect(page.getByLabel('Maya online',{exact:true}).first()).toBeVisible()
  await expect(page.getByLabel('Sophie online',{exact:true}).first()).toBeVisible()
  await sceneReply(page,"I haven't shared it publicly.")
  await click(page,'RETURN TO SOPHIE');await page.clock.runFor(120000)
  await expect(page.locator('[data-scene-node="OPEN-S04-C08"]')).toBeVisible()
  await expect(page.getByText('Sorry about the group.',{exact:true})).toHaveCount(1)
})

test('Scene 04 index selection survives reload; Archive selections create separately labelled sources without player bubbles',async({page})=>{
  await seedScene(page,new Scene04Fixture().at('OPEN-S04-ARCHIVE-GATE').save)
  await click(page,'Open The Archive');await click(page,'OPEN INDEX')
  await click(page,"It's a reference that might be connected.")
  await flush(page);await page.reload();await click(page,'Enter the archive');await click(page,'Open The Archive')
  await expect(page.getByRole('button',{name:"It's a reference that might be connected.",exact:true})).toHaveAttribute('aria-pressed','true')
  await click(page,'Record selection');await click(page,'ACKNOWLEDGE LIMITATIONS')
  await click(page,'Save the public article and this index entry separately.');await click(page,'Record selection')
  await flush(page)
  const recorded=await page.evaluate(async()=>{
    const db=await new Promise<IDBDatabase>((resolve,reject)=>{const r=indexedDB.open('the-archive-reboot',1);r.onsuccess=()=>resolve(r.result);r.onerror=()=>reject(r.error)})
    const s=await new Promise<any>((resolve,reject)=>{const r=db.transaction('saves').objectStore('saves').get('primary');r.onsuccess=()=>resolve(r.result);r.onerror=()=>reject(r.error)})
    db.close();return {sources:s.evidence,uiBubbles:s.prologue.scene01.messages.filter((m:{id:string})=>/^OPEN-S04-C1[01]-PLAYER/.test(m.id))}
  })
  expect(recorded.sources['EV-PUBLIC-GB-001'].verified).toBe(false)
  expect(recorded.sources['EV-INDEX-GB-041'].verified).toBe(false)
  expect(recorded.sources['EV-PUBLIC-GB-001'].source).toContain('public published copy')
  expect(recorded.sources['EV-INDEX-GB-041'].source).toContain('source UNKNOWN')
  expect(recorded.uiBubbles).toEqual([])
})
