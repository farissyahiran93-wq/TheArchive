  await expect(page.getByText('Match the record title and date first.')).toBeVisible()
  await page.screenshot({ animations: 'disabled', scale: 'css', path: 'qa/phase-03a/investigation-390x844.png' })
  await page.getByRole('button', { name: 'Escort: June Ellis → blank' }).click()
  await expect(page.getByText('Not yet established: which complete version was certified')).toBeVisible()
  await page.getByRole('button', { name: 'Recheck comparison' }).click()
