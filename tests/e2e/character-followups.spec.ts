import { expect, test } from '@playwright/test'

test('public-fact private contacts and consented group reunion persist without duplicate members', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-08T09:45:00Z') })
  await page.goto('/?legacyopening=1')
  await page.getByRole('button', { name: "Open Sophie's new message" }).click()
  await page.getByLabel('Your name').fill('Alex')
  await page.getByRole('button', { name: 'Set up phone' }).click()
  // Stop authored timers and finish the registration write before replacing the fixture.
  await page.clock.pauseAt(await page.evaluate(() => Date.now()))
  await expect.poll(() => page.evaluate(() => sessionStorage.getItem('the-archive-reboot:pending-save:v1'))).toBeNull()
  await page.evaluate(async () => {
    const db = await new Promise<IDBDatabase>((resolve, reject) => { const request = indexedDB.open('the-archive-reboot', 1); request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error) })
    await new Promise<void>((resolve, reject) => {
      const tx = db.transaction('saves', 'readwrite')
      const store = tx.objectStore('saves')
      const request = store.get('primary')
      request.onsuccess = () => {
        const save = request.result
        store.put({ ...save, e01: { ...save.e01, sceneId: 'E01-S17', s16OfferSeen: true }, knowledge: { ...save.knowledge, player: [...save.knowledge.player, 'K01'] }, deliveredEvents: [...save.deliveredEvents, 'EV-E01-S12-EDITOR-CHECK', 'CONN-E01-01'], prologue: { ...save.prologue, dialogueVersion: 4, stage: 'complete', step: 2, noteSeen: true, restored: true, indexCompared: true, social: { creator: 'sophie', createdAt: Date.now() - 120_000, phase: 'done', members: ['maya','player'], messages: [{ id: 'OPEN-GROUP-LUCAS-1', sender: 'lucas', text: 'What is your source?', at: Date.now() - 60_000 }, { id: 'OPEN-GROUP-LUCAS-LEFT', sender: 'system', text: 'Lucas left the group.', at: Date.now() - 30_000 }] } } }, 'primary')
      }
      tx.oncomplete = () => resolve()
      tx.onerror = () => reject(tx.error)
    })
    db.close()
  })
  await page.goto('/?legacyopening=1')
  await page.getByRole('button', { name: 'Enter the archive' }).click()
  await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')))
  await page.clock.runFor(15_000)
  await page.getByRole('button', { name: 'Open Messages' }).first().click()
  await expect(page.getByRole('button', { name: 'Open Lucas Grey conversation' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Open Eli Ward conversation' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Open Lucas Grey conversation' }).click()
  await page.getByRole('button', { name: 'Send introduction' }).click()
  await page.getByRole('button', { name: 'Back to inbox' }).click()
  await page.clock.runFor(12_000)
  await page.getByRole('button', { name: 'Open Lucas Grey conversation' }).click()
  await expect(page.getByText('I left because a cropped page was starting to sound like a verdict.', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Can you verify either full version?' }).click()
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await page.clock.runFor(12_000)
  await page.getByRole('button', { name: 'Back to inbox' }).click()
  await expect(page.getByRole('button', { name: 'Open Eli Ward conversation' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Open Nora Vance conversation' })).toBeVisible()
  await page.clock.runFor(12_000)
  await page.getByRole('button', { name: 'Open FIND DANIEL group conversation' }).click()
  await expect(page.getByText('we can bring him back here to compare only the two public Bus 4 views', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Keep the conversation private for now.' }).click()
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await page.getByRole('button', { name: 'Yes. Invite Lucas to compare the public fields only.' }).click()
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await page.clock.runFor(12_000)
  await expect(page.getByText('Lucas rejoined FIND DANIEL.')).toHaveCount(1)
  await page.reload()
  await page.getByRole('button', { name: 'Enter the archive' }).click()
  await page.getByRole('button', { name: 'Open Messages' }).first().click()
  await page.getByRole('button', { name: 'Open FIND DANIEL group conversation' }).click()
  await expect(page.getByText('Lucas rejoined FIND DANIEL.')).toHaveCount(1)
  await page.getByRole('button', { name: 'Back to inbox' }).click()
  await page.getByRole('button', { name: 'Open Eli Ward conversation' }).click()
  await page.getByRole('button', { name: 'Send introduction' }).click()
  await page.clock.runFor(12_000)
  await expect(page.getByText("It can't recreate the missing bytes.", { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Does a damaged E—I field identify a person?' }).click()
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await page.clock.runFor(12_000)
  await expect(page.getByText('Check the complete field and its source', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Back to inbox' }).click()
  await page.getByRole('button', { name: 'Open Nora Vance conversation' }).click()
  await page.getByRole('button', { name: 'Send introduction' }).click()
  await page.clock.runFor(12_000)
  await page.getByRole('button', { name: 'What can I infer from that difference?' }).click()
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await page.clock.runFor(12_000)
  await expect(page.getByText('Only that the public views differ.', { exact: false })).toBeVisible()
})

