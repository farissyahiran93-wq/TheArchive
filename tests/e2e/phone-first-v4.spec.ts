test('a saved earlier opening continues without fabricating the new unknown-number event', async ({ page }) => {
  await page.goto('/?legacyopening=1')
  await page.getByRole('button', { name: "Open Sophie's new message" }).click()
  await page.getByLabel('Your name').fill('Alex')
  await page.getByRole('button', { name: 'Set up phone' }).click()
  await page.getByRole('button', { name: 'Who is Daniel Mercer?' }).click()
  await page.getByRole('button', { name: 'Send message' }).click()
  await page.goto('/')
  await page.getByRole('button', { name: 'Enter the archive' }).click()
  await expect(page.getByRole('region', { name: 'Sophie Mercer first contact' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'You can add me. I will listen first.' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Open unknown message' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Go home' }).click()
  await expect(page.getByRole('main', { name: "Alex's home screen" })).toBeVisible()
})
