import { expect, test } from '@playwright/test'

test('new game starts on a free phone, unknown contact arrives once, and the early recovery remains pending', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-08T08:40:00Z') })
  await page.goto('/')
  await page.getByRole('button', { name: 'Enter the archive' }).click()
  await expect(page.getByRole('main', { name: 'Phone home screen' })).toBeVisible()
  await expect(page.getByLabel('Your name')).toHaveCount(0)
  await page.getByRole('button', { name: 'Open Contacts' }).click()
  await expect(page.getByText('No contacts yet.')).toBeVisible()
  await page.clock.runFor(20_000)
  await expect(page.getByText('No contacts yet.')).toBeVisible()
  await page.getByRole('button', { name: 'Back to home' }).click()
  await expect(page.getByRole('button', { name: 'Open unknown message' })).toBeVisible()
  await page.getByRole('button', { name: 'Open unknown message' }).click()
  await expect(page.getByRole('region', { name: 'Unknown number conversation' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Who is this?' })).toBeVisible()
  await page.getByRole('button', { name: 'Who is this?' }).click()
  await expect(page.locator('.opening-bubble.player')).toHaveCount(0)
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await page.clock.runFor(15_000)
  await expect(page.getByLabel('Your name')).toBeVisible()
  await page.getByLabel('Your name').fill('慧')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await page.clock.runFor(15_000)
  await page.getByRole('button', { name: 'Just use my name' }).click()
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await page.clock.runFor(15_000)
  await page.getByRole('button', { name: 'Why did he leave you my number?' }).click()
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await page.clock.runFor(30_000)
  await expect(page.getByRole('button', { name: 'Open first page photo from unknown number' })).toBeVisible()
  await expect(page.getByText('RECOVERY: ECHO-7/14')).toHaveCount(0)
  await page.getByRole('button', { name: 'Open first page photo from unknown number' }).click()
  await expect(page.getByRole('dialog', { name: 'First page photo' })).toBeVisible()
  await page.getByRole('button', { name: 'Close photo' }).click()
  await page.getByRole('button', { name: 'Back to inbox' }).click()
  await page.getByRole('button', { name: 'Back to home' }).click()
  await page.getByRole('button', { name: 'Open Alerts' }).click()
  await expect(page.getByText('Protected connection request', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Reject pending request' })).toBeVisible()
  await page.getByRole('button', { name: 'Reject pending request' }).click()
  await expect(page.getByText('Request declined.')).toBeVisible()
  await page.getByRole('button', { name: 'Back to home' }).click()
  await page.getByRole('button', { name: 'Open Messages' }).first().click()
  await expect(page.getByRole('button', { name: 'Open FIND DANIEL group conversation' })).toBeVisible()
  await page.getByRole('button', { name: 'Open FIND DANIEL group conversation' }).click()
  await expect(page.getByText('Sophie created the group FIND DANIEL.')).toHaveCount(1)
  await expect(page.getByText('Sophie added Maya Chen, Lucas Grey and Eli Ward.')).toHaveCount(1)
  await page.reload()
  await page.getByRole('button', { name: 'Enter the archive' }).click()
  await page.getByRole('button', { name: 'Open Messages' }).first().click()
  await page.getByRole('button', { name: 'Open FIND DANIEL group conversation' }).click()
  await expect(page.getByText('Sophie created the group FIND DANIEL.')).toHaveCount(1)
})

