import { test,expect,type Page } from '@playwright/test'
import { NaturalFixture } from '../helpers/naturalConversation'
import { naturalInquiryQuestions } from '../../src/content/naturalConversation'
import type { GameSave } from '../../src/game/types'
import { seedScene,sceneReply } from './scene01-helper'

const click=(p:Page,name:string)=>p.getByRole('button',{name,exact:true}).first().click()
const home=(p:Page)=>click(p,'Go home')
const unknown=async(p:Page)=>{await click(p,'Open Messages');await p.getByRole('button',{name:/Open Chapter 1 Unknown Sender conversation/}).click();await p.clock.runFor(120000)}
const runtime=(p:Page):Promise<GameSave>=>p.evaluate(async()=>{const path='/src/game/store.ts';const m=await import(path);return m.useGameStore.getState().save})
const flush=(p:Page)=>p.waitForFunction(()=>!sessionStorage.getItem('the-archive-reboot:pending-save:v1'))
test.use({reducedMotion:'reduce'})

for(const width of [320,430])test(`natural source conversation, Scene 6 lock and private register close at ${width}px`,async({page})=>{
  test.setTimeout(180000)
  await page.setViewportSize({width,height:850})
  const f=new NaturalFixture().bridge().install().scan()
  await seedScene(page,f.save)
  await click(page,'Open TRACE')
  await expect(page.getByRole('button',{name:'REVIEW VERSION HISTORY',exact:true})).toHaveCount(0)
  await home(page);await unknown(page)
  for (const reply of [
    "Who is this? And how do you know what I've read?",
    'Why should I trust an anonymous number with a file about Daniel?',
    'Does this mean someone changed the article?',
    'TRACE? What is that supposed to be?',
    "And I'm supposed to install software from someone who won't even give me a name?",
    "All right. Send the package. I'll decide after I see the warning.",
  ]) await sceneReply(page, reply)
  await expect(page.getByText('What did TRACE actually show you?',{exact:true})).toBeVisible()
  await expect(page.getByRole('region',{name:'Current lead'})).toHaveCount(0)
  await expect(page.locator('.opening-action-heading .guidance-dot')).toHaveCount(1)
  await sceneReply(page,"The article ID matches. But the original text isn't there.")
  await expect(page.getByRole('button',{name:'OPEN BULLETIN ARTICLE',exact:true})).toBeVisible()
  await expect(page.getByText(/INSPECT FIRST/)).toHaveCount(0)
  await click(page,'OPEN BULLETIN ARTICLE')
  await expect(page.getByRole('button',{name:'Mark as read',exact:true})).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Article read',exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'PUBLIC CORRECTIONS REGISTER',exact:true})).toHaveCount(0)
  await click(page,'Updated: Yesterday')
  await expect(page.getByRole('button',{name:'SAVE ANALYSIS TO TRACE'}).locator('.guidance-dot')).toHaveCount(1)
  await click(page,'SAVE ANALYSIS TO TRACE');await click(page,'Close article information')
  expect((await runtime(page)).chapter1!.versionHistory!.chatChoices?.s05_c02_update_label).toBeUndefined()
  await click(page,'RETURN TO CHAT');await page.clock.runFor(120000)
  await sceneReply(page,"It says the page was updated. It doesn't say what changed.")
  // The explicit bridge findings already satisfy index inspection; no new scan.
  await sceneReply(page,"It's a pointer. It doesn't contain the original body.")
  await expect(page.locator('.natural-context button')).toHaveText('OPEN BULLETIN POLICY')
  await click(page,'OPEN BULLETIN POLICY');await click(page,'READ POLICY')
  const before=await runtime(page)
  expect(before.chapter1!.versionHistory!.chatChoices?.s05_c04_policy_meaning).toBeUndefined()
  await click(page,'RETURN TO CHAT');await page.clock.runFor(120000)
  const policy="It doesn't give us a change log for Daniel's article."
  await click(page,policy)
  await expect(page.getByRole('button',{name:'Send',exact:true}).locator('.guidance-dot')).toHaveCount(1)
  await flush(page);await page.reload();await click(page,'Unlock phone');await unknown(page)
  await expect(page.getByRole('button',{name:policy,exact:true})).toHaveAttribute('aria-pressed','true')
  await click(page,'Send');await page.clock.runFor(120000)
  await sceneReply(page,"We have an update label, a reference, and a policy. Not a before-and-after copy.")
  await sceneReply(page,"I'd look for an independently dated copy before contacting anyone.")
  await sceneReply(page,'The references match, but a wording change remains unverified.')
  const locked=await runtime(page)
  expect(locked.chapter1!.versionHistory!.complete).toBe(true)
  expect(locked.chapter1!.correctionsDesk).toBeUndefined()
  await expect(page.getByRole('button',{name:'OPEN PUBLIC REGISTER',exact:true})).toBeDisabled()
  await page.screenshot({path:test.info().outputPath(`instruction-locked-${width}.png`),animations:'disabled'})
  await sceneReply(page,"I'll record what it says, without jumping to conclusions.")
  await click(page,'OPEN PUBLIC CORRECTIONS REGISTER')
  await expect(page.getByRole('button',{name:'ASK THE DESK',exact:true})).toHaveCount(0)
  await expect(page.getByRole('button',{name:'SAVE FINDING',exact:true}).locator('.guidance-dot')).toHaveCount(1)
  await click(page,'SAVE FINDING')
  const saved=await runtime(page)
  expect(saved.chapter1!.correctionsDesk!.complete).toBe(false)
  expect(saved.evidence['NOTE-S06-DESK-LIMITS'].verified).toBe(false)
  await page.screenshot({path:test.info().outputPath(`register-private-${width}.png`),animations:'disabled'})
  await click(page,'RETURN TO CHAT');await page.clock.runFor(120000)
  await sceneReply(page,"Nothing is listed, but that doesn't prove the article stayed the same.")
  await sceneReply(page,"I'd rather not contact the publisher yet.")
  const complete=await runtime(page)
  expect(complete.chapter1!.correctionsDesk!.complete).toBe(true)
  expect(complete.chapter1!.completed).toContain(6)
  expect(complete.deliveredEvents).not.toContain('R-GB-CD-002')
  expect(complete.chapter1!.versionHistory!.checklist).toEqual([])
  expect(complete.chapter2Access).toBeUndefined()
  await expect(page.getByRole('button',{name:'OPEN OPTIONAL REQUEST',exact:true})).toBeDisabled()
  await page.screenshot({path:test.info().outputPath(`conversation-complete-${width}.png`),animations:'disabled'})
  expect(await page.locator('.device').evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true)
})

test('optional inquiry needs its sent opt-in, selected question, review and final Send Request',async({page})=>{
  const f=new NaturalFixture().main().authorize().register().send('a')
  await seedScene(page,f.save);await unknown(page)
  await click(page,"I'll send a specific question through the public desk.")
  await expect(page.getByRole('button',{name:'OPEN OPTIONAL REQUEST',exact:true})).toBeDisabled()
  await click(page,'Send');await page.clock.runFor(120000)
  await click(page,'OPEN OPTIONAL REQUEST')
  await click(page,naturalInquiryQuestions[1])
  expect((await runtime(page)).deliveredEvents).not.toContain('R-GB-CD-002')
  await click(page,'REVIEW REQUEST')
  expect((await runtime(page)).deliveredEvents).not.toContain('R-GB-CD-002')
  await flush(page);await page.reload();await click(page,'Unlock phone')
  await unknown(page);await click(page,'OPEN OPTIONAL REQUEST')
  await expect(page.locator('.vh-draft')).toHaveText(naturalInquiryQuestions[1])
  await click(page,'SEND REQUEST')
  await expect(page.getByRole('heading',{name:'REQUEST SUBMITTED',exact:true})).toBeVisible()
  const save=await runtime(page)
  expect(save.deliveredEvents.filter(id=>id==='R-GB-CD-002')).toHaveLength(1)
  expect(save.pendingEvents.some(e=>e.id==='CH1-S06-DESK-REPLY')).toBe(false)
  await page.screenshot({path:test.info().outputPath('optional-request-receipt.png'),animations:'disabled'})
})
