test('locked text is excluded from search and password entry fits a reduced visual viewport', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await start(page)
  await openApp(page, 'Notes')
  await page.getByLabel('Search Notes').fill('signed index says fourteen')
  await expect(page.getByText('No results')).toBeVisible()
  await page.getByLabel('Search Notes').fill('')
  await page.getByRole('button', { name: 'Locked Note \u2014 revision copy', exact: true }).click()
  await page.getByLabel('Password', { exact: true }).focus()
  await page.setViewportSize({ width: 375, height: 480 })
  await page.getByLabel('Password', { exact: true }).fill('ECHO-7/14')
  await page.getByRole('button', { name: 'Unlock', exact: true }).click()
  await expect(page.getByText(/The signed index says fourteen/)).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'qa/iphone-redesign/apps/password-375x480.png', animations: 'disabled' })
})

test('Daniel home, conversation navigation and device exit use the existing phone shell', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await start(page)
  await expect(page.locator('.mirror-hero')).toHaveCount(0)
  await expect(page.locator('.status-bar')).toHaveCount(1)
  await expect(page.locator('.mirror-dock .mirror-icon')).toHaveCount(4)
  await expect(page.locator('.mirror-icon')).toHaveCount(11)
  await page.screenshot({ path: 'qa/iphone-redesign/apps/daniel-home-redesign-390.png', animations: 'disabled' })
  await openApp(page, 'Messages')
  await expect(page.getByLabel('iMessage conversation')).toHaveCount(0)
  await page.locator('.mirror-file').first().click()
  await expect(page.getByLabel('iMessage conversation')).toBeVisible()
  await expect(page.locator('.mirror input, .mirror textarea')).toHaveCount(0)
  await page.screenshot({ path: 'qa/iphone-redesign/apps/daniel-messages-redesign-390.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(page.locator('.mirror-file')).toHaveCount(4)
  await page.getByRole('button', { name: 'Daniel phone home', exact: true }).click()
  await expect(page.locator('.mirror-dock')).toBeVisible()
  await page.getByRole('button', { name: 'My phone', exact: true }).click()
  await expect(page.getByRole('main', { name: "Rae's home screen" })).toBeVisible()
})
