import { mkdirSync } from 'node:fs'
import { expect, test, type Page } from '@playwright/test'
import { completeOpening } from './opening-helper'

mkdirSync('qa/iphone-redesign/apps', { recursive: true })
async function start(page: Page) {
  await page.goto('/?legacyopening=1')
  await page.getByRole('button', { name: "Open Sophie's new message" }).click()
  await page.getByLabel('Your name').fill('Rae')
  await page.getByRole('button', { name: 'Set up phone' }).click()
  await completeOpening(page)
  await page.getByRole('button', { name: 'Open The Archive', exact: true }).click()
}
async function openApp(page: Page, name: string) { await page.locator('.mirror-icon').filter({ hasText: name }).click() }
async function phone(page: Page) { await page.getByRole('button', { name: 'Daniel phone home', exact: true }).click() }

for (const width of [320, 375, 390, 430]) {
  test(`recovered Photos, metadata and image viewer work at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 780 })
    await start(page)
    await openApp(page, 'Photos')
    await expect(page.getByLabel('Albums')).toBeVisible()
    await page.locator('.mirror-file').first().click()
    await page.getByRole('button', { name: 'View photos' }).click()
    const viewer = page.getByRole('dialog', { name: 'Photo viewer' })
    await expect(viewer.getByRole('heading', { name: 'Shelf photo', exact: true })).toBeVisible()
    await expect(viewer.getByRole('region', { name: 'Photo details' })).toHaveCount(0)
    await viewer.getByRole('button', { name: 'Photo info', exact: true }).click()
    await expect(viewer.getByText('Unknown', { exact: true })).toHaveCount(2)
    await viewer.getByRole('button', { name: 'Photo info', exact: true }).click()
    await expect(viewer.locator('img')).toBeVisible()
    await expect.poll(() => viewer.locator('img').evaluate(image => (image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
    await viewer.getByRole('button', { name: 'Zoom in', exact: true }).click()
    await expect(viewer.getByLabel('Zoom level')).toHaveText('150%')
    await viewer.getByRole('button', { name: 'Fit image', exact: true }).click()
    await expect(viewer.getByLabel('Zoom level')).toHaveText('100%')
    await viewer.getByRole('button', { name: 'Save to Case Board' }).click()
    await expect(viewer.getByRole('button', { name: 'Saved to Case Board' })).toBeDisabled()
    await page.screenshot({ path: `qa/iphone-redesign/apps/media-${width}.png`, animations: 'disabled' })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await viewer.getByRole('button', { name: 'Back to album' }).click()
    await page.getByRole('button', { name: 'Back', exact: true }).click()
    await page.getByRole('button', { name: 'Hidden Album \u00b7 Index fragments', exact: true }).click()
    await expect(page.getByText(/Two cropped images:/)).toHaveCount(0)
    await page.getByLabel('Password', { exact: true }).fill('wrong')
    await page.getByRole('button', { name: 'Unlock', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('No progress lost')
    await page.getByRole('button', { name: 'Need a hint?' }).click()
    await page.getByRole('button', { name: 'Another hint' }).click()
    await page.getByRole('button', { name: 'Another hint' }).click()
    await expect(page.getByRole('list', { name: 'Password hints' }).locator('li')).toHaveCount(3)
    await page.getByLabel('Password', { exact: true }).fill('7-14')
    await page.getByRole('button', { name: 'Unlock', exact: true }).click()
    await expect(page.getByRole('button', { name: 'View Index crop 01', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'View photos' }).click()
    await viewer.getByRole('button', { name: 'Photo info', exact: true }).click()
    await expect(viewer.getByText(/Two cropped images:/)).toBeVisible()
    await page.keyboard.press('Escape')
    await page.reload()
    await page.getByRole('button', { name: /Enter the archive/i }).click()
    await page.getByRole('button', { name: 'Open The Archive', exact: true }).click()
    await page.getByRole('button', { name: 'Resume Photos' }).click()
    await expect(page.getByRole('button', { name: 'View Index crop 01', exact: true })).toBeVisible()
    await phone(page)
    await expect(page.locator('.mirror-icon')).toHaveCount(11)
    for (const app of ['Messages', 'Mail', 'Phone', 'Notes', 'Files', 'Browser', 'Contacts', 'Maps', 'Archive Index', 'Protected']) {
      await openApp(page, app)
      await expect(page.getByRole('heading', { name: app, exact: true })).toBeVisible()
      expect(await page.locator('.mirror').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
      await page.screenshot({ path: `qa/iphone-redesign/apps/${app.toLowerCase().replaceAll(' ', '-')}-${width}.png`, animations: 'disabled' })
      await phone(page)
    }

  })
}

