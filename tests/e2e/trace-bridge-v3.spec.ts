import { expect, test, type Page } from '@playwright/test'
import { traceBridgePrefix } from '../../src/content/traceBridgeV3'
import { NaturalFixture, naturalScene04 } from '../helpers/naturalConversation'
import { seedScene, sceneReply } from './scene01-helper'

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true }).first()
const persist = (page: Page) => page.waitForFunction(() => !sessionStorage.getItem('the-archive-reboot:pending-save:v1'))

async function openUnknown(page: Page) {
  await button(page, 'Open Messages').click()
  await page.getByRole('button', { name: /Open Chapter 1 Unknown Sender conversation/ }).click()
  await page.clock.runFor(120_000)
}

test('an installed update replaces the unanswered old Unknown preview from the reported checkpoint', async ({ page }) => {
  const old = new NaturalFixture().tickOne().origin('open')
  await seedScene(page, old.save)
  await openUnknown(page)
  await expect(page.getByText("There's something else you can check.", { exact: true })).toHaveCount(1)
  await expect(page.getByText("You've seen the Greyhaven Bulletin article.", { exact: true })).toHaveCount(0)
  await expect(button(page, "I'll check the reference.")).toHaveCount(0)
  await expect(button(page, 'OPEN TRACE')).toHaveCount(0)
  await expect(button(page, "Who is this? And how do you know what I've read?")).toBeVisible()
  await expect(button(page, 'Send')).toBeDisabled()
})

test('V3 bridge keeps agency through deferral, simulated install, field comparison and the first sent report', async ({ page }) => {
  test.setTimeout(180_000)
  await page.setViewportSize({ width: 320, height: 800 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  const f = naturalScene04().at('complete04')
  f.save.settings.reduceMotion = false
  await seedScene(page, f.save)
  await expect(page.getByRole('main', { name: /home screen/ })).toBeVisible()
  await expect(button(page, 'Open TRACE')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Open notification from Unknown Number' })).toContainText('New message', { timeout: 12_000 })
  await expect(page.getByRole('region', { name: 'Unknown Number conversation' })).toHaveCount(0)
  await openUnknown(page)
  await expect(button(page, 'Send')).toBeDisabled()
  await sceneReply(page, 'An anomaly? That sounds conveniently vague.')
  await expect(page.getByText("It is vague. Because the record is incomplete, and I won't fill in what isn't there.", { exact: true })).toBeVisible()
  await sceneReply(page, 'You could have made that reference yourself.')
  await sceneReply(page, 'What makes a reference different from the actual document?')
  await sceneReply(page, 'Another app? Did you make it?')
  await expect(page.getByText("I built the viewer. I didn't create the index it reads.", { exact: true })).toBeVisible()
  await sceneReply(page, "How do I know TRACE isn't altering the results?")
  await sceneReply(page, "I'm not installing an unknown app right now.")
  await expect(button(page, 'INSPECT PACKAGE')).toHaveCount(0)
  await button(page, 'Go home').click()
  await openUnknown(page)
  await sceneReply(page, 'Send TRACE again. I want to check the reference.')
  await button(page, 'INSPECT PACKAGE').click()
  const security = page.getByRole('dialog', { name: 'Device security' })
  await expect(security).toContainText('Publisher: UNKNOWN')
  await expect(security).toContainText('Integrity: NOT ESTABLISHED')
  await button(page, 'NOT NOW').click()
  await expect(security).toHaveCount(0)
  await button(page, 'INSPECT PACKAGE').click()
  await button(page, 'INSTALL').click()
  await page.clock.runFor(2300)
  await expect(security).toContainText('Reading package manifest')
  await page.keyboard.press('Escape')
  await expect(security).toHaveCount(0)
  await button(page, 'INSPECT PACKAGE').click()
  await button(page, 'INSTALL').click()
  await page.clock.runFor(2300)
  await persist(page)
  await page.reload()
  await page.clock.runFor(9000)
  await expect(security).toContainText('Installation complete.')
  await button(page, 'DONE').click()
  await button(page, 'Unlock phone').click()
  await openUnknown(page)
  await expect(page.getByText("Open TRACE when you're ready.", { exact: true })).toHaveCount(1)
  await button(page, 'Go home').click()
  await button(page, 'Open TRACE').click()
  await button(page, 'INSPECT REFERENCE').click()
  await expect(page.getByText('Target: ARC-IDX-GB-041', { exact: false })).toBeVisible()
  await button(page, 'SCAN REFERENCE').click()
  await page.clock.runFor(2200)
  const progress = page.getByRole('progressbar', { name: 'Reference trace progress' })
  expect(Number(await progress.getAttribute('value'))).toBeGreaterThan(0)
  expect(Number(await progress.getAttribute('value'))).toBeLessThan(100)
  await page.keyboard.press('Escape')
  await button(page, 'INSPECT REFERENCE').click()
  await expect(button(page, 'RESUME REFERENCE TRACE')).toBeVisible()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await button(page, 'RESUME REFERENCE TRACE').click()
  await button(page, 'VIEW FINDINGS').click()
  await page.getByRole('button', { name: /^TITLE · / }).click()
  await expect(page.getByText('Titles can match without proving identity. Try the article identifier.')).toBeVisible()
  await page.getByRole('button', { name: /^PUBLIC_ARTICLE · / }).click()
  await button(page, 'COMPARE WITH PUBLIC COPY').click()
  await expect(page.getByRole('definition').filter({ hasText: 'GB-ARTICLE-001' })).toHaveCount(2)
  await expect(page.getByText('SOURCE NOT AUTHENTICATED', { exact: true })).toBeVisible()
  await button(page, 'RETURN TO MESSAGES').click()
  await page.clock.runFor(120_000)
  await expect(page.locator('.scene01-chat')).toHaveAttribute('data-scene-node', traceBridgePrefix + 'C08')
  await expect(button(page, 'Send')).toBeDisabled()
  await expect(button(page, 'OPEN BULLETIN ARTICLE')).toHaveCount(0)
  const report = "The article ID matches. But the original text isn't there."
  await button(page, report).click()
  await expect(button(page, 'OPEN BULLETIN ARTICLE')).toHaveCount(0)
  await button(page, 'Send').click()
  await page.clock.runFor(120_000)
  await button(page, 'OPEN BULLETIN ARTICLE').click()
  await expect(button(page, 'Article read')).toBeVisible()
  await expect(button(page, 'PUBLIC CORRECTIONS REGISTER')).toHaveCount(0)
  await button(page, 'Updated: Yesterday').click()
  await expect(button(page, 'SAVE ANALYSIS TO TRACE')).toBeEnabled()
})
