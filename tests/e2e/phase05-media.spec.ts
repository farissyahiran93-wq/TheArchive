import { mkdirSync } from 'node:fs'
import { expect, test, type Page } from '@playwright/test'
import { completeOpening } from './opening-helper'

mkdirSync('qa/phase-05', { recursive: true })
async function start(page: Page) {
  await page.goto('/?legacyopening=1')
  await page.getByRole('button', { name: "Open Sophie's new message" }).click()
  await page.getByLabel('Your name').fill('Rae')
  await page.getByRole('button', { name: 'Set up phone' }).click()
  await completeOpening(page)
  await page.getByRole('button', { name: 'Open The Archive', exact: true }).click()
  await page.locator('.mirror-icon').filter({ hasText: 'Gallery' }).click()
  await page.locator('.mirror-file').first().click()
}
async function unlock(page: Page, album: string, answer: string) {
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  await page.getByRole('button', { name: album, exact: true }).click()
  await page.getByLabel('Password', { exact: true }).fill(answer)
  await page.getByRole('button', { name: 'Unlock', exact: true }).click()
}

test('all six PNGs render in their own albums without requesting locked pixels or verifying them', async ({ page }) => {
  const requested: string[] = []
  page.on('request', request => { if (request.url().includes('/media/gallery/')) requested.push(request.url()) })
  await start(page)
  const viewer = page.getByRole('dialog', { name: 'Recovered media viewer' })
  expect(requested.some(url => /03-index|04-index|05-notice|06-map/.test(url))).toBe(false)
  await expect(page.locator('img[src*="03-index"],img[src*="04-index"],img[src*="05-notice"],img[src*="06-map"]')).toHaveCount(0)
  for (const title of ['Shelf photo', 'Message crop']) {
    if (title === 'Message crop') { await page.getByRole('button', { name: 'Back', exact: true }).click(); await page.getByRole('button', { name: 'Screenshot \u2014 message fragment', exact: true }).click() }
    await page.getByRole('button', { name: `View ${title}`, exact: true }).click()
    await expect.poll(() => viewer.locator('img').evaluate(image => (image as HTMLImageElement).naturalWidth)).toBeGreaterThan(1000)
    await expect(viewer.getByText('Not recovered', { exact: true })).toBeVisible()
    expect(await viewer.getByLabel('Image pan area').evaluate(el => el.scrollHeight <= el.clientHeight + 1)).toBe(true)
    await viewer.getByRole('button', { name: 'Back to album', exact: true }).focus()
    await page.keyboard.press('Shift+Tab')
    await expect(viewer.getByRole('button', { name: 'Save recovered observation', exact: true })).toBeFocused()
    await viewer.getByRole('button', { name: 'Back to album' }).click()
  }
  await unlock(page, 'Hidden Album \u00b7 Index fragments', '7-14')
  expect(requested.some(url => /05-notice|06-map/.test(url))).toBe(false)
  await page.getByRole('button', { name: 'View Index crop 01', exact: true }).click()
  await expect(viewer.getByRole('heading', { name: 'Index crop 01', exact: true })).toBeVisible()
  await viewer.getByRole('button', { name: 'Next image', exact: true }).click()
  await expect(viewer.getByRole('heading', { name: 'Index crop 02', exact: true })).toBeVisible()
  await expect.poll(() => viewer.locator('img').evaluate(image => (image as HTMLImageElement).naturalWidth)).toBe(1120)
  await expect(viewer).not.toContainText('June Ellis')
  await viewer.getByRole('button', { name: 'Zoom in', exact: true }).click()
  await expect(viewer.getByLabel('Zoom level')).toHaveText('150%')
  await viewer.getByRole('button', { name: 'Previous image', exact: true }).click()
  await expect(viewer.getByLabel('Zoom level')).toHaveText('100%')
  await viewer.getByRole('button', { name: 'Save recovered observation', exact: true }).click()
  await viewer.getByRole('button', { name: 'Back to album' }).click()
  await unlock(page, 'Hidden Album \u00b7 Quay references', 'NORTHQUAY')
  await page.getByRole('button', { name: 'View Notice-board photo', exact: true }).click()
  await expect.poll(() => viewer.locator('img').evaluate(image => (image as HTMLImageElement).naturalWidth)).toBe(1425)
  await viewer.getByRole('button', { name: 'Next image', exact: true }).click()
  await expect.poll(() => viewer.locator('img').evaluate(image => (image as HTMLImageElement).naturalWidth)).toBe(1080)
  await viewer.getByRole('button', { name: 'Save recovered observation', exact: true }).click()
  await page.screenshot({ path: 'qa/phase-05/map-viewer.png' })
  await viewer.getByRole('button', { name: 'Back to album' }).click()
  await page.getByRole('button', { name: 'Evidence', exact: true }).click()
  await expect(page.getByText('gallery / OBSERVATION / UNVERIFIED')).toHaveCount(2)
  await page.getByRole('button', { name: 'View retained Hidden Album \u00b7 Quay references', exact: true }).click()
  await expect(viewer.getByRole('heading', { name: 'Notice-board photo', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.reload()
  await page.getByRole('button', { name: /Enter the archive/i }).click()
  await page.getByRole('button', { name: 'Open The Archive', exact: true }).click()
  await page.getByRole('button', { name: 'Resume recovered gallery', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Observation saved - unverified', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'View Map screenshot', exact: true })).toBeVisible()
})

test('unavailable full image has retry and caption fallback without losing album navigation', async ({ page }) => {
  await page.route('**/media/gallery/01-shelf-photo.png', route => route.abort())
  await start(page)
  await page.getByRole('button', { name: 'Open full-screen record', exact: true }).click()
  const viewer = page.getByRole('dialog', { name: 'Recovered media viewer' })
  await expect(viewer.getByText('Image unavailable. The recovered description remains readable.')).toBeVisible()
  await expect(viewer.getByText(/photograph of a document shelf/)).toBeVisible()
  await page.unroute('**/media/gallery/01-shelf-photo.png')
  await viewer.getByRole('button', { name: 'Retry image', exact: true }).click()
  await expect.poll(() => viewer.locator('img').evaluate(image => (image as HTMLImageElement).naturalWidth)).toBe(1425)
  await viewer.getByRole('button', { name: 'Back to album' }).click()
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(page.getByLabel('Recovered album thumbnails')).toBeVisible()
})

test('Sophie portrait loads and uses initial fallback when its asset is unavailable', async ({ page }) => {
  await page.goto('/?legacyopening=1')
  await page.getByRole('button', { name: "Open Sophie's new message" }).click()
  await page.getByLabel('Your name').fill('Rae')
  await page.getByRole('button', { name: 'Set up phone' }).click()
  const avatar = page.locator('.opening-chat-header .character-avatar')
  await expect.poll(() => avatar.locator('img').evaluate(image => (image as HTMLImageElement).naturalWidth)).toBe(160)
  await page.screenshot({ path: 'qa/phase-05/sophie-portrait.png' })
  await page.route('**/media/portraits/sophie-avatar.webp', route => route.abort())
  await page.reload()
  await page.getByRole('button', { name: /Enter the archive/i }).click()
  await expect(avatar).toHaveText('S')
  await expect(avatar.locator('img')).toHaveCount(0)
})
