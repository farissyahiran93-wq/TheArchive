import { expect, test } from '@playwright/test'
import { completeOpening } from './opening-helper'

test('Daniel Notes and Gallery are partly public and locked item passwords persist', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/?legacyopening=1')
  await page.getByRole('button', { name: "Open Sophie's new message" }).click()
  await page.getByLabel('Your name').fill('Rae')
  await page.getByRole('button', { name: 'Set up phone' }).click()
  await completeOpening(page)
  await page.getByRole('button', { name: 'Open The Archive' }).click()
  await page.locator('.mirror-icon').filter({ hasText: 'Notes' }).click()
  await expect(page.getByText('2 accessible · 2 locked')).toBeVisible()
  await page.getByRole('button', { name: /Locked Note — revision copy/ }).click()
  await expect(page.getByText('The signed index says fourteen')).toHaveCount(0)
  await page.getByRole('button', { name: 'Need a hint?' }).click()
  await expect(page.getByText(/Sophie has something physical/)).toBeVisible()
  await page.getByLabel('Password', { exact: true }).fill('incorrect')
  await page.getByRole('button', { name: 'Unlock', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Incorrect password')
  await page.getByLabel('Password', { exact: true }).fill('ECHO-7/14')
  await page.getByRole('button', { name: 'Unlock', exact: true }).click()
  await expect(page.getByText('The signed index says fourteen')).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: /Enter the archive/i }).click()
  await page.getByRole('button', { name: 'Open The Archive' }).click()
  await page.locator('.mirror-icon').filter({ hasText: 'Notes' }).click()
  await page.getByRole('button', { name: /Locked Note — revision copy/ }).click()
  await expect(page.getByText('The signed index says fourteen')).toBeVisible()
  await page.getByRole('button', { name: "Daniel's Phone" }).click()
  await page.locator('.mirror-icon').filter({ hasText: 'Gallery' }).click()
  await expect(page.getByText('2 accessible · 2 locked')).toBeVisible()
  await page.getByRole('button', { name: 'Hidden Album \u00b7 Index fragments', exact: true }).click()
  await expect(page.getByText(/two cropped images/i)).toHaveCount(0)
  await page.getByLabel('Password', { exact: true }).fill('7-14')
  await page.getByRole('button', { name: 'Unlock', exact: true }).click()
  await expect(page.getByText(/Two cropped images/i)).toBeVisible()
})
