import { expect, test } from '@playwright/test'

test('a delayed invitation resumes as a distrustful group, preserves departures, and returns to Sophie privately', async ({ page }) => {
  await page.goto('/?legacyopening=1')
  await page.getByRole('button', { name: "Open Sophie's new message" }).click()
  await page.getByLabel('Your name').fill('Rae')
  await page.getByRole('button', { name: 'Set up phone' }).click()
  await page.getByRole('button', { name: 'Who is Daniel Mercer?' }).click()
  await page.getByRole('button', { name: 'Send message' }).click()
  await page.getByRole('button', { name: 'Give me a moment before you add me.' }).click()
  await page.getByRole('button', { name: 'Send message' }).click()
  await expect(page.getByRole('region', { name: 'FIND DANIEL group conversation' })).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: /Enter the archive/i }).click()
  await expect(page.getByRole('button', { name: 'You can add me. I will listen first.' })).toBeVisible()
  await page.getByRole('button', { name: 'You can add me. I will listen first.' }).click()
  await page.getByRole('button', { name: 'Send message' }).click()
  await page.reload()
  await page.getByRole('button', { name: /Enter the archive/i }).click()
  await expect(page.getByRole('region', { name: 'FIND DANIEL group conversation' })).toBeVisible()
  await expect(page.getByText('Sophie added you to FIND DANIEL.')).toHaveCount(1)
  await expect(page.getByText('Who is this? What did Daniel actually tell you?')).toBeVisible()
  await expect(page.locator('.opening-group-line.player')).toHaveCount(0)
  await expect(page.getByText("Daniel's handwritten note")).toHaveCount(0)
  await page.getByRole('button', { name: 'How do I know any of you knew Daniel?' }).click()
  await page.getByRole('button', { name: 'Send message' }).click()
  await page.getByRole('button', { name: "You're blaming me for a decision Sophie made." }).click()
  await page.getByRole('button', { name: 'Send message' }).click()
  await expect(page.getByText('Lucas left the group.')).toBeVisible()
  await expect(page.getByRole('button', { name: "Why didn't you show the group?" })).toBeVisible()
  await page.getByRole('button', { name: 'Go home' }).click()
  await page.getByRole('button', { name: 'Open Messages' }).first().click()
  await page.getByRole('button', { name: 'Open FIND DANIEL group conversation' }).click()
  await expect(page.getByText('Lucas left the group.')).toBeVisible()
  await expect(page.getByText('Sophie left the group.')).toBeVisible()
  await page.getByRole('button', { name: 'Back to inbox' }).click()
  await page.getByRole('button', { name: 'Open Sophie Mercer conversation' }).click()
  await page.getByRole('button', { name: "Why didn't you show the group?" }).click()
  await page.getByRole('button', { name: 'Send message' }).click()
  await expect(page.getByRole('button', { name: /Daniel's handwritten note/ })).toBeVisible()
  await page.getByRole('button', { name: 'Go home' }).click()
  await page.getByRole('button', { name: 'Open Contacts' }).click()
  await expect(page.getByText('Sophie Mercer')).toBeVisible()
  await expect(page.getByText('Maya Chen')).toHaveCount(0)
})
