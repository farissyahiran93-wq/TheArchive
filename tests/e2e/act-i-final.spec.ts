import { test,expect } from '@playwright/test'
import { ActIFinalFixture } from '../helpers/actIFinal'
import { seedScene,openSophie,sceneReply } from './scene01-helper'
test.use({ reducedMotion:'reduce' })

test('all nineteen FINAL Sophie decisions finish on Goodnight and the later article conversation waits for a manual action',async({page})=>{
  test.setTimeout(150000)
  await seedScene(page,new ActIFinalFixture().until('OPEN-S03-C01').save)
  await openSophie(page)
  for(let number=1;number<=19;number++){
    await expect(page.locator('.scene01-chat')).toHaveAttribute('data-scene-node',`OPEN-S03-C${String(number).padStart(2,'0')}`)
    const count=await page.locator('.opening-bubble.player').count()
    await page.locator('.scene01-options .opening-choice').first().click()
    await expect(page.locator('.opening-bubble.player')).toHaveCount(count)
    await page.getByRole('button',{name:'Send',exact:true}).click()
    await page.clock.runFor(180000)
  }
  await expect(page.getByText('Goodnight.',{exact:true})).toHaveCount(1)
  await expect(page.getByText('I found that article. The one I mentioned.',{exact:true})).toHaveCount(1)
  await expect(page.locator('[data-scene-node="OPEN-S03-FINAL-COMPLETE"]')).toBeVisible()
  await page.getByRole('button',{name:'Continue conversation →',exact:true}).click()
  await page.clock.runFor(120000)
  await expect(page.locator('[data-scene-node="OPEN-S04-C01"]')).toBeVisible()
  await expect(page.getByRole('article',{name:'Public article link'})).toHaveCount(0)
})

test('final Scene 01: defer, resume, explicit Continue, JOIN and manual group opening on a small phone',async({page})=>{
  await page.setViewportSize({width:320,height:720})
  await seedScene(page,new ActIFinalFixture().until('OPEN-S01-C13').save)
  await openSophie(page)
  await sceneReply(page,'Not right now.')
  await expect(page.getByRole('button',{name:'Accept invitation',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Accept invitation',exact:true}).click()
  await page.clock.runFor(120000)
  await page.getByRole('button',{name:'Continue',exact:true}).click()
  await page.clock.runFor(120000)
  await sceneReply(page,'I can handle a rude person.')
  await page.getByRole('button',{name:'JOIN GROUP',exact:true}).click()
  await expect(page.getByRole('button',{name:'Open FIND DANIEL →',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Open FIND DANIEL →',exact:true}).click()
  await page.clock.runFor(120000)
  await expect(page.locator('[data-scene-node="OPEN-S02-C01"]')).toBeVisible()
  await expect(page.getByText('You joined FIND DANIEL.',{exact:true})).toHaveCount(1)
  expect(await page.locator('.opening-thread').evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true)
})

test('final Scene 02: private sender request preserves group, block and reload, then manual return',async({page})=>{
  await seedScene(page,new ActIFinalFixture().until('OPEN-S02-C09').save)
  await page.getByRole('button',{name:'Open Messages',exact:true}).first().click()
  await page.getByRole('button',{name:'Open FIND DANIEL group conversation',exact:true}).click()
  await sceneReply(page,'What happened that night?')
  await expect(page.getByRole('button',{name:'OPEN MESSAGE',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'OPEN MESSAGE',exact:true}).click()
  await expect(page.getByText("You shouldn't be talking to her.",{exact:true})).toHaveCount(1)
  await page.getByRole('button',{name:'Who is this?',exact:true}).click()
  await page.getByRole('button',{name:'Send',exact:true}).click()
  await page.getByRole('button',{name:'BLOCK NUMBER',exact:true}).click()
  await page.getByRole('button',{name:'BACK TO FIND DANIEL',exact:true}).click()
  await page.clock.runFor(120000)
  await expect(page.locator('[data-scene-node="OPEN-S02-C10"]')).toBeVisible()
  await expect(page.getByText('Maya deleted a message.',{exact:true})).toHaveCount(1)
  await expect(page.getByText("You shouldn't be talking to her.",{exact:true})).toHaveCount(0)
  await page.waitForFunction(()=>!sessionStorage.getItem('the-archive-reboot:pending-save:v1'))
  await page.reload()
  await page.getByRole('button',{name:'Enter the archive',exact:true}).click()
  await page.getByRole('button',{name:'Open Messages',exact:true}).first().click()
  await page.getByRole('button',{name:'Open Chapter 1 Unknown Sender conversation',exact:true}).click()
  await expect(page.getByText('Number blocked.',{exact:true})).toBeVisible()
  await expect(page.getByText('Who is this?',{exact:true})).toHaveCount(1)
})

test('final Scene 03: disclosure and secondary choices each require Send and survive reload',async({page})=>{
  const f=new ActIFinalFixture().until('OPEN-S02-C09').send('a').sender().act('open-group').until('OPEN-S03-FINAL-DISCLOSURE-OFFER')
  await seedScene(page,f.save)
  await openSophie(page)
  await page.getByRole('button',{name:'TELL SOPHIE ABOUT THE MESSAGE',exact:true}).click()
  await sceneReply(page,'Something strange happened while we were in the group.')
  // Authored apostrophes are literal; selection must not send the continuation automatically.
  const continuation=page.getByRole('button',{name:/A number I don't know sent me/})
  await expect(continuation).toBeVisible()
  await continuation.click()
  expect(await page.locator('.opening-bubble.player').filter({hasText:/A number I don't know/}).count()).toBe(0)
  await page.getByRole('button',{name:'Send',exact:true}).click()
  await page.clock.runFor(120000)
  await sceneReply(page,'During the group chat.')
  await expect(page.getByRole('button',{name:"I replied, but they haven't answered.",exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:"I didn't reply.",exact:true}).click()
  await page.waitForFunction(()=>!sessionStorage.getItem('the-archive-reboot:pending-save:v1'))
  await page.reload()
  await page.getByRole('button',{name:'Enter the archive',exact:true}).click()
  await openSophie(page)
  await expect(page.getByRole('button',{name:"I didn't reply.",exact:true})).toHaveAttribute('aria-pressed','true')
  await page.getByRole('button',{name:'Send',exact:true}).click()
  await page.clock.runFor(120000)
  await expect(page.locator('[data-scene-node="OPEN-S03-C16"]')).toBeVisible()
  await expect(page.getByText('Thanks for telling me.',{exact:true})).toHaveCount(1)
})
