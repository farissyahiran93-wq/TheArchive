import { completeOpening } from './opening-helper'
import { expect, test } from '@playwright/test'

test('no-tip civilian completes private research, then sends a minimal late tip without repeating GCRO', async ({ page }) => {
  test.setTimeout(60_000)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/?legacyopening=1')
  await page.getByRole('button',{ name: /Enter the archive/i }).click()
  await page.getByLabel('Your name').fill('Rae')
  await page.getByRole('button',{ name: /Set up phone/i }).click()
  await completeOpening(page)
  await page.getByRole('button',{ name: 'Open Bulletin' }).last().click()
  for (const name of ['Read public brief','Read full brief','Older preview','Pin June row as an observation','View current copy','Compare copies','Escort: June Ellis → blank',"I don't know what happened.",'Save lead to private Board','Keep researching without sending a tip']) await page.getByRole('button',{ name, exact: true }).click()
  await expect(page.getByRole('heading',{ name: 'Public research path' })).toBeVisible()
  await page.getByRole('button',{ name: /Older Bus 4 preview.*Memory Project/ }).click()
  await page.getByRole('button',{ name: 'Cropped preview; original not held here.', exact: true }).click()
  await page.getByRole('button',{ name: 'The preview displays a 24 Nov verification stamp.' }).click()
  for (const [date,label] of [['23 Nov 2019','event'],['24 Nov 2019 15:20','stamp'],['3 Oct 2026','transfer'],['7 Oct 2026','publication']]) await page.getByLabel(`Label ${date}`).selectOption(label)
  await page.getByRole('button',{ name: 'Save date carriers' }).click()
  await page.getByRole('button',{ name: 'Open civic portal revision history' }).click()
  await page.getByRole('button',{ name: 'Correction approval.' }).click()
  for (const text of ['23 Nov 2019 · Bus 4 record date','24 Nov 2019 15:20 · v1 verification shown on crop and notice','25 Nov 2019 08:40 · v2 correction approval']) await page.getByRole('button',{ name: text }).click()
  await page.getByRole('button',{ name: 'The archived v1 escort field is intact.' }).click()
  await page.getByRole('button',{ name: 'Uncertain' }).click()
  await page.getByRole('button',{ name: 'Check the archived field and revision trail.' }).click()
  await page.getByLabel('Search public Greyhaven index').fill('Bus 4 2019 version')
  for (const id of ['SR-02','SR-04','SR-01']) {
    await page.locator('article.utility-card').filter({ hasText: id }).getByRole('button',{ name: 'Open result · inspect publisher' }).click()
    await page.getByRole('button',{ name: new RegExp(`^${id} ·`) }).click()
  }
  await page.getByRole('button',{ name: 'Save source map' }).click()
  await page.getByRole('button',{ name: 'Continue to public request' }).click()
  await expect(page.getByText("Open Maya's optional check-in")).toHaveCount(0)
  await page.getByRole('button',{ name: 'Redacted v1/v2 lineage and public escort field.' }).click()
  await page.getByRole('button',{ name: 'Review request' }).click()
  await page.getByRole('button',{ name: 'Submit request' }).click()
  await expect(page.getByRole('heading',{ name: 'Four pages, one claim' })).toBeVisible()
  await page.getByRole('button',{ name: 'Open GCRO-REG-01 office directory' }).click()
  for (let pageNumber=1;pageNumber<=4;pageNumber++) await page.getByRole('button',{ name: `Open page ${pageNumber} of 4` }).click()
  for (const name of ['GCRO duty records officer · GCRO-REG-01','Same root record ID, v1 snapshot, correction reference, v2 public reference','Pages 1–4 and RED-041 suppression list','This one-use request session and its own delivery record']) await page.getByRole('button',{ name }).click()
  await page.getByRole('button',{ name: 'Validate release · R04' }).click()
  for (const source of ['E012','E003','E002']) await page.getByRole('button',{ name: new RegExp(`^${source} ·`) }).click()
  await page.getByRole('button',{ name: 'Save corroborated finding' }).click()
  await page.getByRole('button',{ name: 'Compare public directory and open status card' }).click()
  await page.getByRole('button',{ name: 'The role can still submit correction work.' }).click()
  await expect(page.getByRole('button',{ name: 'End episode' })).toHaveCount(0)
  await page.getByRole('button',{ name: 'Prepare public-observation tip' }).click()
  await expect(page.getByRole('button',{ name: 'Use an anonymous return token.' })).not.toHaveAttribute('class', /selected/)
  await page.getByRole('button',{ name: 'Use an anonymous return token.' }).click()
  await page.getByRole('button',{ name: 'Review recipient and privacy' }).click()
  await expect(page.getByText('GCRO-EXP-20261008-041')).toHaveCount(0)
  await page.getByRole('button',{ name: 'Send tip' }).click()
  await page.getByRole('button',{ name: 'Open reply inbox' }).click()
  await page.getByRole('button',{ name: 'Check public editor listing' }).click()
  await page.getByRole('button',{ name: 'Case code and return route' }).click()
  await page.getByRole('button',{ name: 'Return to saved finding' }).click()
  await page.getByRole('button',{ name: 'End episode' }).click()
  await expect(page.getByText('THE ARCHIVE · EPISODE 01 COMPLETE')).toBeVisible()
  const facts = await page.evaluate(async () => {
    const db = await new Promise<IDBDatabase>((resolve,reject) => { const req=indexedDB.open('the-archive-reboot',1); req.onsuccess=()=>resolve(req.result); req.onerror=()=>reject(req.error) })
    const result = await new Promise<{r01:number;r04:number;k02:boolean;mayaFacts:string[];exportDisclosed:boolean}>((resolve,reject) => { const req=db.transaction('saves').objectStore('saves').get('primary'); req.onsuccess=()=>{const save=req.result;resolve({r01:save.deliveredEvents.filter((id:string)=>id==='R01').length,r04:save.deliveredEvents.filter((id:string)=>id==='R04').length,k02:save.knowledge.player.includes('K02'),mayaFacts:save.knowledge.characters.maya,exportDisclosed:save.messages.some((m:{attachmentIds?:string[]})=>m.attachmentIds?.includes('E012'))})};req.onerror=()=>reject(req.error) })
    db.close();return result
  })
  expect(facts.r01).toBe(1)
  expect(facts.r04).toBe(1)
  expect(facts.k02).toBe(true)
  expect(facts.mayaFacts).not.toContain('K02.public-finding')
  expect(facts.exportDisclosed).toBe(false)
})
