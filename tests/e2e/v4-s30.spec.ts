import { expect, test } from '@playwright/test'
import { openSophie, sceneAt, sceneReply, seedScene } from './scene01-helper'
import { completeOpening } from './opening-helper'

test('earlier saved source data stays stored while the old transcript and note photo are replaced', async ({ page }) => {
  await page.goto('/?legacyopening=1')
  await page.getByRole('button', { name: "Open Sophie's new message" }).click()
  await page.getByLabel('Your name').fill('Rae')
  await page.getByRole('button', { name: 'Set up phone' }).click()
  await completeOpening(page)
  await page.goto('/')
  await page.getByRole('button', { name: 'Enter the archive', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Open The Archive', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Open Photos', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Open photo from Sophie', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Back to home', exact: true }).click()
  await page.getByRole('button', { name: 'Open Messages', exact: true }).first().click()
  await page.getByRole('button', { name: 'Open Unknown number conversation', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Sophie first contact conversation' })).toBeVisible()
  await expect(page.locator('.opening-bubble').filter({ hasText: 'ECHO-7/14' })).toHaveCount(0)
})

test('declining the group persists and voluntary acceptance plays the warning before explicit JOIN GROUP', async ({ page }) => {
  await seedScene(page, sceneAt('13', { '08': 'b' }))
  await openSophie(page)
  await sceneReply(page, 'No. This is getting too weird.')
  await expect(page.getByRole('button', { name: 'Accept invitation', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'JOIN GROUP', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'NOT NOW', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Enter the archive', exact: true }).click()
  await openSophie(page)
  await page.getByRole('button', { name: 'View invitation', exact: true }).click()
  await page.getByRole('button', { name: 'Accept invitation', exact: true }).click()
  await page.clock.runFor(120_000)
  await expect(page.locator('.opening-bubble.sophie').filter({ hasText: 'I saw you accepted.' })).toBeVisible()
  await sceneReply(page, 'I can handle it.')
  await expect(page.getByRole('button', { name: 'JOIN GROUP', exact: true })).toBeVisible()
  await page.screenshot({ path: 'qa/scene01/invitation.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'JOIN GROUP', exact: true }).click()
  await page.clock.runFor(180_000)
  await expect(page.getByRole('region', { name: 'FIND DANIEL group conversation' })).toBeVisible()
  await expect(page.locator('.opening-bubble.sophie').nth(0)).toHaveText('Hey, everyone.')
  await expect(page.locator('.opening-bubble.sophie').nth(1)).toHaveText('Before anyone says anything...')
  await expect(page.locator('.opening-bubble.sophie').nth(2)).toHaveText('I added someone.')
  await expect(page.getByRole('button', { name: "Hi. I'm just as confused as you are.", exact: true })).toBeVisible()
  await expect(page.getByText('Daniel and I are engaged.', { exact: false })).toHaveCount(0)
  await expect(page.locator('.chat-attachment')).toHaveCount(0)
})
