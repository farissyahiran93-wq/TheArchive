import { completeOpening } from './opening-helper'
import { mkdirSync } from 'node:fs'
import { expect, test, type Page } from '@playwright/test'

mkdirSync('qa/phase-03b',{ recursive: true })

async function reachEditor(page: Page) {
  await page.goto('/?legacyopening=1')
  await page.getByRole('button', { name: /Enter the archive/i }).click()
  await page.getByLabel('Your name').fill('Rae')
  await page.getByRole('button', { name: /Set up phone/i }).click()
  await completeOpening(page)
  await page.getByRole('button', { name: 'Open Bulletin' }).last().click()
  await page.getByRole('button', { name: 'Read public brief' }).click()
  await page.getByRole('button', { name: 'Read full brief' }).click()
  await page.getByRole('button', { name: 'Older preview' }).click()
  await page.getByRole('button', { name: 'Pin June row as an observation' }).click()
  await page.getByRole('button', { name: 'View current copy' }).click()
  await page.getByRole('button', { name: 'Compare copies' }).click()
  await page.getByRole('button', { name: 'Escort: June Ellis → blank' }).click()
  await page.getByRole('button', { name: "I don't know what happened." }).click()
  await page.getByRole('button', { name: 'Save lead to private Board' }).click()
  await page.getByRole('button', { name: 'Use an anonymous return token.' }).click()
  await page.getByRole('button', { name: 'Review recipient and privacy' }).click()
  await page.getByRole('button', { name: 'Send tip' }).click()
  await page.getByRole('button', { name: 'Open reply inbox' }).click()
  await page.getByRole('button', { name: 'Check public editor listing' }).click()
  await page.getByRole('button', { name: 'Case code and return route' }).click()
  await expect(page.getByRole('heading', { name: 'Channel checked' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Continue to the exact row' })).toBeEnabled()
}

test('quiet source route reaches the public editor note without R02 or unsolicited Maya question', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await reachEditor(page)
  await page.getByRole('button', { name: 'Continue to the exact row' }).click()
  await expect(page.getByRole('button', { name: 'Ask Maya' })).toBeVisible()
  await expect(page.getByText("Was the blank field on the portal page itself, or in another screenshot?")).toHaveCount(0)
  await page.getByRole('button', { name: 'Continue public source' }).click()
  await expect(page.getByText("Could you send me what you're reading?", { exact: false })).toHaveCount(0)
  await page.getByRole('button', { name: 'Not now. No image or text sent.' }).click()
  await page.getByRole('button', { name: 'Continue without sharing' }).click()
  await expect(page.getByText('Maya received no new message or attachment.')).toBeVisible()
  await page.getByRole('button', { name: 'Open editor note' }).click()
  await expect(page.getByText('Editor note, 7 Oct:', { exact: false })).toBeVisible()
  await expect(page.getByText('A transfer record can support that Maya received this crop.', { exact: false })).toBeVisible()
  await expect(page.getByText("He sent it on the third with a short note:", { exact: false })).toHaveCount(0)
  const state = await page.evaluate(async () => {
    const db = await new Promise<IDBDatabase>((resolve,reject) => { const req = indexedDB.open('the-archive-reboot',1); req.onsuccess = () => resolve(req.result); req.onerror = () => reject(req.error) })
    const result = await new Promise<{ scene: string; r02: number; mayaKnows: boolean }>((resolve,reject) => { const req = db.transaction('saves').objectStore('saves').get('primary'); req.onsuccess = () => resolve({ scene: req.result.e01.sceneId, r02: req.result.deliveredEvents.filter((id: string) => id === 'R02').length, mayaKnows: req.result.knowledge.characters.maya.includes('R02.public-escort-row') }); req.onerror = () => reject(req.error) })
    db.close(); return result
  })
  expect(state).toEqual({ scene: 'E01-S15', r02: 0, mayaKnows: false })
  await page.screenshot({ path: 'qa/phase-03b/editor-note-quiet-390x844.png', animations: 'disabled', scale: 'css' })
})

test('explicit text-only R02 and sender scope survive reload', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await reachEditor(page)
  await page.getByRole('button', { name: 'Continue to the exact row' }).click()
  await page.getByRole('button', { name: 'Ask Maya' }).click()
  await expect(page.getByText('Was the blank field on the portal page itself, or in another screenshot?')).toBeVisible()
  await page.getByRole('button', { name: 'On the civic portal page. I opened the link from your brief.' }).click()
  await expect(page.getByText('You · sent')).toHaveCount(0)
  await page.getByRole('button', { name: /^Send$/ }).click()
  await expect(page.getByText('You · sent')).toHaveCount(1)
  await page.getByRole('button', { name: 'Continue public source' }).click()
  await expect(page.getByText("Could you send me what you're reading?", { exact: false })).toBeVisible()
  await page.getByRole('button', { name: /^Text only: the older preview/ }).click()
  await expect(page.getByText('R02 · text only')).toHaveCount(0)
  await page.getByRole('button', { name: /^Send$/ }).click()
  await expect(page.getByText('R02 · text only')).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: /Enter the archive/i }).click()
  await page.getByRole('button', { name: 'Open Bulletin' }).last().click()
  await expect(page.getByText('R02 · text only')).toBeVisible()
  const scope = await page.evaluate(async () => {
    const db = await new Promise<IDBDatabase>((resolve,reject) => { const req = indexedDB.open('the-archive-reboot',1); req.onsuccess = () => resolve(req.result); req.onerror = () => reject(req.error) })
    const result = await new Promise<{ receipts: number; attachment: unknown; mayaKnows: string[] }>((resolve,reject) => { const req = db.transaction('saves').objectStore('saves').get('primary'); req.onsuccess = () => resolve({ receipts: req.result.deliveredEvents.filter((id: string) => id === 'R02').length, attachment: req.result.messages.find((m: {id:string}) => m.id === 'player.C02-SHARE.B').attachmentIds, mayaKnows: req.result.knowledge.characters.maya }); req.onerror = () => reject(req.error) })
    db.close(); return result
  })
  expect(scope.receipts).toBe(1)
  expect(scope.attachment).toBeUndefined()
  expect(scope.mayaKnows).toContain('R02.public-escort-row')
  expect(scope.mayaKnows).not.toContain('K02')
})
