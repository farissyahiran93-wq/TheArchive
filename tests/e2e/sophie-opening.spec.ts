import { finishGroupOpening, finishRecoveryConversation, finishSophieDisclosure } from './opening-helper'
import { expect, test } from '@playwright/test'

/** End-to-end acceptance test for the new default opening (no shortcut). */
test('Sophie contacts the player, Daniel note unlocks a read-only mirror and leads to the missing entry', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/?legacyopening=1')
  await expect(page.getByRole('button', { name: "Open Sophie's new message" })).toBeVisible()
  await page.getByRole('button', { name: "Open Sophie's new message" }).click()
  await page.getByLabel('Your name').fill('Rae')
  await page.getByRole('button', { name: 'Set up phone' }).click()
  await expect(page.getByRole('region', { name: 'Sophie Mercer first contact' })).toBeVisible()
  await expect(page.getByText('My brother Daniel gave me this number before he disappeared.')).toBeVisible()
  await expect(page.locator('.opening-bubble.player')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Send message' })).toBeDisabled()
  await page.getByRole('button', { name: 'Why would he give you my number?' }).click()
  await expect(page.locator('.opening-bubble.player')).toHaveCount(0)
  await page.getByRole('button', { name: 'Send message' }).click()
  await expect(page.locator('.opening-bubble.player')).toHaveCount(1)
  await finishGroupOpening(page)
  await page.getByRole('button', { name: /Daniel's handwritten note/ }).click()
  await expect(page.getByText('RECOVERY: ECHO-7/14', { exact: true })).toBeHidden()
  await page.getByText('Read text', { exact: true }).click()
  await expect(page.getByText('RECOVERY: ECHO-7/14')).toBeVisible()
  await page.screenshot({ path: 'test-results/sophie-note-390.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Save note to evidence' }).click()
  await page.reload()
  await page.getByRole('button', { name: /Enter the archive/i }).click()
  await page.getByRole('button', { name: /Daniel's handwritten note/ }).click()
  await expect(page.getByText('Note saved · token identified')).toBeVisible()
  await page.getByRole('button', { name: 'Close photo' }).click()
  await page.getByRole('button', { name: 'Did he explain the recovery token?' }).click()
  await page.getByRole('button', { name: 'Send message' }).click()
  await expect(page.getByRole('button', { name: 'Restore The Archive' })).toHaveCount(0)
  await finishRecoveryConversation(page)
  await page.getByRole('button', { name: 'Not yet - review Sophie conversation' }).click()
  await page.getByRole('button', { name: 'Review recovery offer' }).click()
  await page.getByRole('button', { name: 'Inspect permission & origin' }).click()
  await expect(page.getByText(/no access to your contacts, actual email or phone files/i)).toBeVisible()
  await page.getByRole('button', { name: 'Restore The Archive' }).click()
  await expect(page.getByLabel("Daniel Mercer's phone")).toBeVisible()
  await page.getByRole('button', { name: 'My phone', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Open The Archive' })).toBeVisible()
  await page.getByRole('button', { name: 'Open The Archive' }).click()
  await page.locator('.mirror-icon').filter({ hasText: 'Archive Index' }).click()
  await page.locator('.mirror-file').first().click()
  await expect(page.getByRole('button', { name: 'Read the Untitled Note and Index report' })).toBeDisabled()
  await page.getByRole('button', { name: "Daniel's Phone" }).click()
  await page.locator('.mirror-icon').filter({ hasText: 'Notes' }).click()
  await page.locator('.mirror-file').first().click()
  await expect(page.getByText(/Check the source\. Check the revisions/)).toBeVisible()
  await page.getByRole('button', { name: "Daniel's Phone" }).click()
  await page.locator('.mirror-icon').filter({ hasText: 'Archive Index' }).click()
  await page.locator('.mirror-file').first().click()
  await page.getByRole('button', { name: 'Record the missing-entry discrepancy' }).click()
  await expect(page.getByText('Did you find something?', { exact: true })).toBeVisible()
  await finishSophieDisclosure(page)
  await page.getByRole('button', { name: 'Continue the investigation' }).click()
  await expect(page.getByRole('main', { name: "Rae's home screen" })).toBeVisible()
  await page.getByRole('button', { name: 'Open The Archive' }).click()
  await expect(page.getByLabel("Daniel Mercer's phone")).toBeVisible()
  await page.getByRole('button', { name: 'My phone' }).click()
  await page.getByRole('button', { name: 'Open Messages' }).first().click()
  await page.getByRole('button', { name: 'Open Sophie Mercer conversation' }).click()
  await expect(page.getByText(/Did you find something\?/)).toBeVisible()
})
