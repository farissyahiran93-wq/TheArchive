import { expect, test } from '@playwright/test'
import { finishGroupOpening } from './opening-helper'

test('phone settings persist, contacts and photos follow discovery, and confirmed restart preserves preferences', async ({ page }) => {
  await page.goto('/?legacyopening=1')
  await page.evaluate(() => localStorage.setItem('the-archive:game-save:v1', 'legacy-sentinel'))
  await page.getByRole('button', { name: "Open Sophie's new message" }).click()
  await page.getByLabel('Your name').fill('Rae')
  await page.getByRole('button', { name: 'Set up phone' }).click()
  await page.getByRole('button', { name: 'Go home' }).click()
  await page.getByRole('button', { name: 'Open Contacts' }).click()
  await expect(page.getByRole('button', { name: /Sophie Mercer Messages/ })).toBeVisible()
  await expect(page.getByText('Maya Chen')).toHaveCount(0)
  await page.getByRole('button', { name: 'Back to home' }).click()
  await page.getByRole('button', { name: 'Open Photos' }).click()
  await expect(page.getByAltText('Greyhaven canal wallpaper')).toBeVisible()
  await expect(page.getByText('From Sophie')).toHaveCount(0)
  await page.getByRole('button', { name: 'Back to home' }).click()
  await page.getByRole('button', { name: 'Open Messages' }).first().click()
  await page.getByRole('button', { name: 'Open Sophie Mercer conversation' }).click()
  await page.getByRole('button', { name: 'Who is Daniel Mercer?' }).click()
  await page.getByRole('button', { name: 'Send message' }).click()
  await finishGroupOpening(page)
  await page.getByRole('button', { name: /Daniel's handwritten note/ }).click()
  await page.getByRole('button', { name: 'Save note to evidence' }).click()
  await page.getByRole('button', { name: 'Go home' }).click()
  await page.getByRole('button', { name: 'Open Photos' }).click()
  await expect(page.getByText('From Sophie')).toBeVisible()
  await page.getByRole('button', { name: 'Back to home' }).click()
  await page.getByRole('button', { name: 'Show home page 2' }).click()
  await page.getByRole('button', { name: 'Open Settings' }).click()
  await page.getByRole('checkbox', { name: 'Sound Effects' }).uncheck()
  await page.getByRole('checkbox', { name: 'Background Music' }).uncheck()
  await page.getByRole('checkbox', { name: 'Reduce Motion' }).check()
  await page.getByRole('button', { name: /Restart Story Start/ }).click()
  await expect(page.getByRole('dialog', { name: 'Restart the story?' })).toBeVisible()
  await page.getByRole('button', { name: 'Cancel' }).click()
  await page.reload()
  await page.getByRole('button', { name: /Enter the archive/i }).click()
  await page.getByRole('button', { name: 'Go home' }).click()
  await page.getByRole('button', { name: 'Show home page 2' }).click()
  await page.getByRole('button', { name: 'Open Settings' }).click()
  await expect(page.getByRole('checkbox', { name: 'Sound Effects' })).not.toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'Background Music' })).not.toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'Reduce Motion' })).toBeChecked()
  await page.getByRole('button', { name: /Restart Story Start/ }).click()
  await page.getByRole('dialog', { name: 'Restart the story?' }).getByRole('button', { name: 'Restart Story' }).click()
  await expect(page.getByRole('button', { name: "Open Sophie's new message" })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('the-archive:game-save:v1'))).toBe('legacy-sentinel')
  expect(await page.evaluate(() => localStorage.getItem('the-archive-reboot:audio:v1'))).toBe('{"effects":false,"music":false}')
  await page.getByRole('button', { name: "Open Sophie's new message" }).click()
  await expect(page.getByLabel('Your name')).toBeVisible()
})

